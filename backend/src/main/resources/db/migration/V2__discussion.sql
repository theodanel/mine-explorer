-- Discussion entre joueurs, en texte libre (200 caractères au plus, filtré par ChatRules avant d'arriver ici).
CREATE TABLE chat_message (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    player_id UUID NOT NULL,
    text VARCHAR(800) NOT NULL,
    sent_at TIMESTAMP WITH TIME ZONE NOT NULL,
    -- Caché par les signalements ou par un modérateur : plus affiché, gardé jusqu'à la purge pour garder une trace
    hidden BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_chat_player FOREIGN KEY (player_id) REFERENCES player (id) ON DELETE CASCADE
);

-- Derniers messages, et purge des anciens
CREATE INDEX idx_chat_sent_at ON chat_message (sent_at);
-- Délai entre deux messages d'un même joueur
CREATE INDEX idx_chat_player_sent_at ON chat_message (player_id, sent_at);

-- Un signalement par joueur et par message : quelques joueurs différents suffisent à cacher un message
CREATE TABLE chat_report (
    message_id BIGINT NOT NULL,
    reporter_id UUID NOT NULL,
    reported_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_chat_report PRIMARY KEY (message_id, reporter_id),
    CONSTRAINT fk_report_message FOREIGN KEY (message_id) REFERENCES chat_message (id) ON DELETE CASCADE,
    CONSTRAINT fk_report_reporter FOREIGN KEY (reporter_id) REFERENCES player (id) ON DELETE CASCADE
);

-- Joueurs coupés de la discussion par un modérateur : ils lisent toujours, mais n'écrivent plus
CREATE TABLE chat_mute (
    player_id UUID PRIMARY KEY,
    muted_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_mute_player FOREIGN KEY (player_id) REFERENCES player (id) ON DELETE CASCADE
);
